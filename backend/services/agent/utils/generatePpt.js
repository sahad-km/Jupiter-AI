import pptxgen from "pptxgenjs";

export const generatePpt = async (data) => {
    const ppt = new pptxgen();
    ppt.layout = "LAYOUT_WIDE"; // 13.33 x 7.5 inches
    ppt.title = data.title || "Jupiter AI Presentation";
    ppt.author = "Jupiter AI";
    ppt.subject = data.title || "Presentation";
    ppt.company = "Jupiter AI";
    ppt.lang = "en-US";
    ppt.theme = {
        headFontFace: "Arial",
        bodyFontFace: "Calibri",
    };

    // 1. Cover Slide
    addCoverPage(ppt, data);

    // 2. Content Slides
    const slides = Array.isArray(data.slides) ? data.slides : [];
    slides.forEach((s, i) => {
        addContentSlide(
            ppt,
            s.title || `Section ${i + 1}`,
            s.points || [],
            i + 1,
            slides.length
        );
    });

    // 3. Thank You Slide
    addThankYouSlide(ppt);

    // Return Node.js Buffer
    return await ppt.write({ outputType: "nodebuffer" });
};

// Also support typo alias if referenced elsewhere
export const genetatePpt = generatePpt;

function addCoverPage(ppt, data) {
    const slide = ppt.addSlide();

    // Dark slate / modern teal gradient feel
    slide.background = { color: "0F172A" };

    // Accent top bar
    slide.addShape(ppt.ShapeType.rect, {
        x: 0,
        y: 0,
        w: "100%",
        h: 0.15,
        fill: { color: "06B6D4" },
        line: { color: "06B6D4" },
    });

    // Main Presentation Title
    slide.addText(data.title || "Jupiter AI Presentation", {
        x: 1.0,
        y: 2.2,
        w: 11.33,
        h: 1.8,
        fontSize: 38,
        fontFace: "Arial",
        bold: true,
        color: "FFFFFF",
        align: "center",
        valign: "middle",
    });

    // Subtitle
    if (data.subtitle) {
        slide.addText(data.subtitle, {
            x: 1.5,
            y: 4.1,
            w: 10.33,
            h: 1.0,
            fontSize: 20,
            fontFace: "Calibri",
            italic: true,
            color: "94A3B8",
            align: "center",
            valign: "top",
        });
    }

    // Footer badge
    slide.addText("Generated by Jupiter AI", {
        x: 1.0,
        y: 6.2,
        w: 11.33,
        h: 0.5,
        fontSize: 12,
        fontFace: "Calibri",
        color: "06B6D4",
        align: "center",
    });
}

function addContentSlide(ppt, title, points, slideIndex, totalSlides) {
    const slide = ppt.addSlide();

    slide.background = { color: "0B0F19" };

    // Accent Header bar
    slide.addShape(ppt.ShapeType.rect, {
        x: 0,
        y: 0,
        w: "100%",
        h: 0.1,
        fill: { color: "06B6D4" },
        line: { color: "06B6D4" },
    });

    // Slide Title
    slide.addText(title, {
        x: 0.8,
        y: 0.6,
        w: 11.7,
        h: 0.9,
        fontSize: 24,
        fontFace: "Arial",
        bold: true,
        color: "38BDF8",
        valign: "middle",
    });

    // Subtle divider under title
    slide.addShape(ppt.ShapeType.line, {
        x: 0.8,
        y: 1.5,
        w: 11.7,
        h: 0,
        line: { color: "1E293B", width: 1.5 },
    });

    // Bullet Points
    if (Array.isArray(points) && points.length > 0) {
        const textObjects = points.map((point) => ({
            text: point,
            options: {
                bullet: { type: "bullet", color: "38BDF8" },
                fontSize: 15,
                fontFace: "Calibri",
                color: "E2E8F0",
                breakLine: true,
                paraSpaceAfter: 12,
            },
        }));

        slide.addText(textObjects, {
            x: 0.8,
            y: 1.8,
            w: 11.7,
            h: 4.8,
            valign: "top",
            lineSpacingMultiple: 1.25,
        });
    }

    // Slide Number Footer
    slide.addText(`Slide ${slideIndex} of ${totalSlides}`, {
        x: 10.5,
        y: 6.8,
        w: 2.0,
        h: 0.4,
        fontSize: 11,
        fontFace: "Calibri",
        color: "64748B",
        align: "right",
    });

    slide.addText("Jupiter AI Presentation", {
        x: 0.8,
        y: 6.8,
        w: 4.0,
        h: 0.4,
        fontSize: 11,
        fontFace: "Calibri",
        color: "64748B",
        align: "left",
    });
}

function addThankYouSlide(ppt) {
    const slide = ppt.addSlide();

    slide.background = { color: "0F172A" };

    slide.addText("Thank You!", {
        x: 1.0,
        y: 2.5,
        w: 11.33,
        h: 1.5,
        fontSize: 42,
        fontFace: "Arial",
        bold: true,
        color: "FFFFFF",
        align: "center",
        valign: "middle",
    });

    slide.addText("Created with Jupiter AI Presentation Designer", {
        x: 1.0,
        y: 4.2,
        w: 11.33,
        h: 0.8,
        fontSize: 18,
        fontFace: "Calibri",
        color: "38BDF8",
        align: "center",
        valign: "top",
    });
}